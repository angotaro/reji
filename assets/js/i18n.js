export const STRINGS = { ja, en };
let lang = 'ja';

export function t(key, vars) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (Array.isArray(s)) s = vars && Number(vars.n) === 1 ? s[0] : s[1];
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

export const getLang = () => lang;

function applyLang() {
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'ja';
  try { localStorage.setItem('reji:lang', lang); } catch { /* ignore */ }
  applyLang();
}

export function initLang() {
  let l = null;
  try { l = localStorage.getItem('reji:lang'); } catch { /* ignore */ }
  if (l !== 'ja' && l !== 'en') {
    const nav = typeof navigator !== 'undefined' ? navigator.language || '' : '';
    l = !nav || /^ja\b/i.test(nav) ? 'ja' : 'en';
  }
  lang = l;
  applyLang();
  return lang;
}

const pad = (n) => String(n).padStart(2, '0');
const WD_JA = ['日', '月', '火', '水', '木', '金', '土'];
const WD_EN = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
const MO_EN = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

export const fmtTime = (ms) => {
  const d = new Date(ms);
  return `${pad(d.getHours())}:${pad(d.getMinutes())}`;
};

export function fmtDay(ms) {
  const d = new Date(ms);
  const thisYear = d.getFullYear() === new Date().getFullYear();
  return lang === 'ja'
    ? `${thisYear ? '' : `${d.getFullYear()}年`}${d.getMonth() + 1}月${d.getDate()}日(${WD_JA[d.getDay()]})`
    : `${WD_EN[d.getDay()]}, ${MO_EN[d.getMonth()]} ${d.getDate()}${thisYear ? '' : `, ${d.getFullYear()}`}`;
}

/** Receipts always carry the full date. */
export function fmtDateTime(ms) {
  const d = new Date(ms);
  return lang === 'ja'
    ? `${d.getFullYear()}年${d.getMonth() + 1}月${d.getDate()}日(${WD_JA[d.getDay()]}) ${fmtTime(ms)}`
    : `${WD_EN[d.getDay()]}, ${MO_EN[d.getMonth()]} ${d.getDate()}, ${d.getFullYear()} ${fmtTime(ms)}`;
}

